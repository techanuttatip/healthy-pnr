export const ALL_OFFICIAL_FORMS: OfficialInspectionFormDef[] = [
  OFFICIAL_FOOD_SERVICE_FORM,
  OFFICIAL_FOOD_STORAGE_FORM,
  OFFICIAL_HAZARDOUS_HEALTH_FORM
];

export function resolveInspectionForm(typeStr?: string, category?: string): OfficialInspectionFormDef {
  const t = (typeStr || '').toLowerCase();
  const cat = (category || '').toLowerCase();
  if (
    cat === 'hazardous' ||
    t.includes('อันตราย') ||
    t.includes('ปิโตรเลียม') ||
    t.includes('น้ำมัน') ||
    t.includes('หยอดเหรียญ') ||
    t.includes('สารเคมี') ||
    t.includes('แก๊ส') ||
    t.includes('ก๊าซ') ||
    t.includes('อู่') ||
    t.includes('ซ่อม') ||
    t.includes('โรงงาน') ||
    t.includes('สัตว์') ||
    t.includes('ฟาร์ม') ||
    t.includes('หมวด ๗') ||
    t.includes('บทส') ||
    t.includes('hazardous')
  ) {
    return OFFICIAL_HAZARDOUS_HEALTH_FORM;
  }
  if (
    cat === 'food_storage' ||
    t.includes('สะสม') ||
    t.includes('ชำ') ||
    t.includes('คลัง') ||
    t.includes('โกดัง') ||
    t.includes('มินิ') ||
    t.includes('สะดวก') ||
    t.includes('ห้องเย็น') ||
    t.includes('storage')
  ) {
    return OFFICIAL_FOOD_STORAGE_FORM;
  }
  return OFFICIAL_FOOD_SERVICE_FORM;
}
